export const AVATAR_ICONS = Object.keys(AVATAR_ICON_PATHS);

const FALLBACK_COLOR = '#0f766e';
const HEX_COLOR = /^#[0-9a-f]{6}$/i;

// Black or white, whichever reads better on the given #RRGGBB background.
function contrastColor(hex: string): string {
  const [red, green, blue] = [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16));
  const luminance = (0.299 * red + 0.587 * green + 0.114 * blue) / 255;
  return luminance > 0.6 ? '#111111' : '#ffffff';
}

export type AvatarProps = {
  icon?: string | null;
  color?: string | null;
  // Shown as an initial when the user has no (known) icon.
  name?: string | null;
  className?: string;
};

export function Avatar({ icon, color, name, className }: AvatarProps) {
  const background = color && HEX_COLOR.test(color) ? color : FALLBACK_COLOR;
  const paths = icon ? AVATAR_ICON_PATHS[icon] : undefined;
  const initial = name?.trim().charAt(0).toUpperCase();

  return (
    <span
      className={[styles.avatar, className].filter(Boolean).join(' ')}
      style={{ backgroundColor: background, color: contrastColor(background) }}
      aria-hidden="true"
    >
      {paths ? (
        <svg
          className={styles.icon}
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2"
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          {paths}
        </svg>
      ) : (
        initial
      )}
    </span>
  );
}
